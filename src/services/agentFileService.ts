import fs from 'node:fs';
import path from 'node:path';

import { AGENTS_DIR } from '../config/env.js';
import { Agent, AgentRole, AutonomyLevel, ModelProvider } from '../models/index.js';
import {
  parseFrontmatter,
  serializeFrontmatter,
  toPromptText,
  hasProse,
  FrontmatterData
} from '../utils/frontmatter.js';
import { logError, logInfo } from '../utils/logger.js';

/**
 * Agent personas as files: `~/.alpha/agents/<agent-id>.md`.
 *
 * AGENTS_AND_MEMORIES_PLAN.md always specified a file layer alongside SQLite and
 * it was never built, so `system_prompt` — one TEXT column, typically one
 * sentence — was the entire instruction an agent received. A column is a bad
 * home for prose: it cannot be diffed, reviewed, versioned, or edited in an
 * editor, so in practice it stayed one sentence long.
 *
 * ## Precedence
 *
 * The file wins for every field it declares; the database supplies the rest.
 * That direction is the whole point — an override the UI silently reverted on
 * the next save would make hand-editing pointless.
 *
 * The opposite hazard is real too: renaming an agent in the UI must not discard
 * a persona someone spent an afternoon writing. So the projection back to disk
 * (`syncAgentFile`) refreshes frontmatter but only replaces the body when the
 * caller says the system prompt itself changed.
 *
 * ## Trust
 *
 * These files are hand-edited, which makes every value here untrusted input.
 * `role`, `provider` and `autonomy` are validated against their unions and
 * dropped when unrecognised rather than passed through to become an argv value
 * or a database write. A malformed file degrades to "database only"; it never
 * fails a run.
 */

/** Frontmatter key → Agent field. Insertion order is the file's key order. */
const FILE_KEYS = {
  name: 'name',
  role: 'role',
  description: 'description',
  provider: 'modelProvider',
  model: 'modelName',
  autonomy: 'autonomyLevel',
  temperature: 'temperature',
  skills: 'skills',
  mcpServers: 'mcpServers',
  /**
   * Appearance, last because it is the least interesting to a reader.
   *
   * Carried so the file is a complete portable definition: an agent exported to
   * a teammate should arrive looking like itself, not as a broken image and a
   * default swatch. Both are ignored by the runner.
   */
  color: 'color',
  avatar: 'avatar'
} as const;

const ROLES: readonly AgentRole[] = [
  'Architect',
  'Coder',
  'Reviewer',
  'QA Tester',
  'DevOps',
  'Triager',
  'Researcher'
];

const PROVIDERS: readonly ModelProvider[] = [
  'Anthropic',
  'OpenAI',
  'Antigravity',
  'Google Gemini',
  'Ollama',
  'LM Studio'
];

const AUTONOMY_LEVELS: readonly AutonomyLevel[] = [
  'Supervised',
  'Semi-Autonomous (Requires Approval)',
  'Full Autonomy'
];

/**
 * Fields a persona file may override.
 *
 * Everything absent here — id, owner, isMine, createdAt, envVars,
 * customCliArgs — stays database-owned: identity, or machine-specific, or
 * secret. `envVars` in particular must never reach the file, because the file
 * is the thing people export and send to each other.
 */
export interface AgentFileOverlay {
  systemPrompt?: string;
  name?: string;
  role?: AgentRole;
  description?: string;
  modelProvider?: ModelProvider;
  modelName?: string;
  autonomyLevel?: AutonomyLevel;
  temperature?: number;
  skills?: string[];
  mcpServers?: string[];
  color?: string;
  avatar?: string;
}

/** How `syncAgentFile` treats an existing body. */
export type BodyPolicy =
  /** Overwrite it — the caller changed the system prompt. */
  | 'replace'
  /** Keep whatever is on disk — the caller changed something else. */
  | 'preserve';

export function agentsRoot(): string {
  fs.mkdirSync(AGENTS_DIR, { recursive: true });
  return AGENTS_DIR;
}

/**
 * Reject an id that would escape the agents directory.
 *
 * Ids are generated by Alpha today, but they also arrive on `POST /api/agents`
 * as `req.body.id`, so a separator or '..' here would write a persona file to an
 * arbitrary path.
 */
function assertId(id: string): string {
  const valid =
    typeof id === 'string' &&
    id.length > 0 &&
    id.length <= 120 &&
    !id.includes('/') &&
    !id.includes('\\') &&
    !id.includes('\0') &&
    id !== '.' &&
    id !== '..';

  if (!valid) throw new Error(`Invalid agent id "${id}" for a persona file path.`);
  return id;
}

export function agentFilePath(id: string): string {
  return path.join(AGENTS_DIR, `${assertId(id)}.md`);
}

export function agentFileExists(id: string): boolean {
  try {
    return fs.existsSync(agentFilePath(id));
  } catch {
    return false;
  }
}

function asString(value: unknown): string | undefined {
  if (typeof value === 'string' && value.trim()) return value.trim();
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  return undefined;
}

function asStringList(value: unknown): string[] | undefined {
  if (Array.isArray(value)) return value.map(v => String(v).trim()).filter(Boolean);
  // A single unquoted value is a plausible hand-edit for a one-item list.
  const single = asString(value);
  return single ? [single] : undefined;
}

/**
 * Match a hand-typed value to a union member, case-insensitively.
 *
 * Someone writing `provider: anthropic` or `role: coder` means the obvious
 * thing, and rejecting it over capitalisation would be a bad experience for a
 * file whose entire purpose is being typed by hand.
 */
function asUnion<T extends string>(
  value: unknown,
  allowed: readonly T[],
  label: string,
  warnings: string[]
): T | undefined {
  const raw = asString(value);
  if (raw === undefined) return undefined;

  const hit = allowed.find(a => a.toLowerCase() === raw.toLowerCase());
  if (!hit) {
    warnings.push(
      `Ignoring unknown ${label} "${raw}" — expected one of: ${allowed.join(', ')}`
    );
    return undefined;
  }
  return hit;
}

function asTemperature(value: unknown, warnings: string[]): number | undefined {
  if (value === undefined || value === '') return undefined;
  const num = typeof value === 'number' ? value : Number(asString(value));
  if (!Number.isFinite(num) || num < 0 || num > 2) {
    warnings.push(
      `Ignoring out-of-range temperature ${JSON.stringify(value)} — expected a number from 0 to 2`
    );
    return undefined;
  }
  return num;
}

/**
 * Parse persona file text into an overlay, collecting anything it had to ignore.
 *
 * Warnings are returned rather than only logged so the editor can put them in
 * front of whoever typed the file — a mistyped `role:` that silently does
 * nothing is the kind of thing you only discover by wondering why an edit had
 * no effect.
 */
export function parseAgentFileContent(raw: string): {
  overlay: AgentFileOverlay | null;
  warnings: string[];
} {
  const warnings: string[] = [];
  const { data, body } = parseFrontmatter(raw);

  const overlay: AgentFileOverlay = {
    name: asString(data.name),
    role: asUnion(data.role, ROLES, 'role', warnings),
    description: asString(data.description),
    modelProvider: asUnion(data.provider, PROVIDERS, 'provider', warnings),
    modelName: asString(data.model),
    autonomyLevel: asUnion(data.autonomy, AUTONOMY_LEVELS, 'autonomy', warnings),
    temperature: asTemperature(data.temperature, warnings),
    skills: asStringList(data.skills),
    mcpServers: asStringList(data.mcpServers),
    color: asString(data.color),
    avatar: asString(data.avatar),
    /**
     * Comments stripped: the generated file explains itself to whoever opens
     * it, and that guidance ("Frontmatter keys override the matching columns in
     * alpha.db") is meaningless to a model and paid for on every request. It
     * stays in the file — only the prompt view drops it.
     *
     * `hasProse` rather than a length check so that a body edited back to
     * nothing but its heading resolves to undefined and falls through to the
     * database column, instead of sending `# Ada Lovelace` as a system prompt.
     */
    systemPrompt: hasProse(body) ? toPromptText(body) : undefined
  };

  // Drop the keys that resolved to nothing so callers can spread this over a
  // database row without blanking columns the file simply did not mention.
  for (const key of Object.keys(overlay) as (keyof AgentFileOverlay)[]) {
    if (overlay[key] === undefined) delete overlay[key];
  }

  return { overlay: Object.keys(overlay).length ? overlay : null, warnings };
}

/**
 * Read a persona file into an overlay, or null when there is no usable file.
 *
 * Never throws for a content problem — a broken persona file must not take an
 * agent offline. Only an invalid id (a programming error) throws.
 */
export function readAgentFile(id: string): AgentFileOverlay | null {
  const raw = readAgentFileRaw(id);
  if (raw === null) return null;

  const { overlay, warnings } = parseAgentFileContent(raw);
  for (const warning of warnings) logError(`Persona file ${id}.md`, warning);

  return overlay;
}

/** The file's text as written, or null when it does not exist. */
export function readAgentFileRaw(id: string): string | null {
  const file = agentFilePath(id);

  try {
    return fs.readFileSync(file, 'utf8');
  } catch (err: any) {
    if (err?.code !== 'ENOENT') {
      logError(`Could not read persona file ${file}`, err?.message ?? String(err));
    }
    return null;
  }
}

/**
 * Largest persona file the editor will save.
 *
 * The body becomes a system prompt paid for on every request, so an accidental
 * paste of a whole document is worth refusing rather than silently billing for.
 */
export const AGENT_FILE_MAX_BYTES = 64 * 1024;

/**
 * Save persona file text exactly as given.
 *
 * Deliberately not merged with `syncAgentFile`: that projects the database row
 * onto disk, whereas this is the person editing the file and their text wins
 * verbatim, frontmatter included. Returns the path written.
 */
export function writeAgentFileRaw(id: string, content: string): string {
  const file = agentFilePath(id);

  if (Buffer.byteLength(content, 'utf8') > AGENT_FILE_MAX_BYTES) {
    throw new Error(`Persona file exceeds ${AGENT_FILE_MAX_BYTES} bytes.`);
  }

  agentsRoot();
  // Normalised to a trailing newline so a later read/serialize round trip does
  // not show a spurious one-line diff.
  fs.writeFileSync(file, content.replace(/\s*$/, '') + '\n', 'utf8');

  return file;
}

function frontmatterFor(agent: Agent): FrontmatterData {
  const data: FrontmatterData = {};

  for (const [fileKey, agentKey] of Object.entries(FILE_KEYS)) {
    const value = (agent as any)[agentKey];
    if (value === undefined || value === null || value === '') continue;
    data[fileKey] = Array.isArray(value) ? value.map(String) : value;
  }

  return data;
}

/**
 * The comment header a generated persona file carries.
 *
 * Written into the body rather than as frontmatter comments because it has to
 * survive a `preserve` sync, and because the body is where someone editing the
 * file is actually looking.
 */
function starterBody(agent: Agent): string {
  const prompt = (agent.systemPrompt ?? '').trim();

  /**
   * Only add a heading when the prompt does not already start with one.
   *
   * The generated body opens with `# {name}`, and that heading is part of the
   * body, so it comes back as part of `systemPrompt` when the file is read.
   * Writing the file again then prepended a second copy. It showed up on the
   * export/import round trip — an imported agent arrived with its name twice,
   * and every further cycle would have added another.
   */
  const heading = prompt.startsWith('#') ? [] : [`# ${agent.name}`, ''];

  return [
    ...heading,
    '<!--',
    '  This file is the system prompt for this agent. Everything below the',
    '  frontmatter is sent to the model verbatim, appended to the CLI\'s own',
    '  default system prompt.',
    '',
    '  Frontmatter keys override the matching columns in alpha.db. Delete a key',
    '  to fall back to whatever the UI has stored.',
    '',
    '  Write the persona below this comment. Headings and comments alone do not',
    '  count as a prompt — with nothing else here, the alpha.db column is used.',
    '-->',
    '',
    prompt
  ]
    .join('\n')
    .trimEnd();
}

/**
 * Project an agent to its persona file.
 *
 * `body: 'preserve'` keeps an existing prose body and refreshes only the
 * frontmatter — the correct behaviour when the UI changed a model or a colour,
 * because the alternative is overwriting a hand-written persona with the one
 * sentence still sitting in the database column.
 *
 * Returns the path written, or null when nothing needed writing.
 */
export function syncAgentFile(agent: Agent, body: BodyPolicy = 'preserve'): string | null {
  try {
    agentsRoot();
    const file = agentFilePath(agent.id);

    let nextBody: string;
    if (body === 'preserve' && fs.existsSync(file)) {
      const existing = parseFrontmatter(fs.readFileSync(file, 'utf8')).body.trim();
      nextBody = existing || starterBody(agent);
    } else {
      nextBody = starterBody(agent);
    }

    fs.writeFileSync(file, serializeFrontmatter(frontmatterFor(agent), nextBody), 'utf8');
    return file;
  } catch (err: any) {
    // A filesystem problem must not fail the database write that triggered this.
    logError(`Could not write persona file for ${agent?.id}`, err?.message ?? String(err));
    return null;
  }
}

export function deleteAgentFile(id: string): boolean {
  try {
    fs.rmSync(agentFilePath(id), { force: true });
    return true;
  } catch (err: any) {
    logError(`Could not delete persona file for ${id}`, err?.message ?? String(err));
    return false;
  }
}

/**
 * Create a persona file for every agent that does not have one.
 *
 * Called at startup so an install that predates this layer — or one whose files
 * were deleted — grows them without the user doing anything. Existing files are
 * left untouched.
 */
export function ensureAgentFiles(agents: Agent[]): number {
  let created = 0;

  for (const agent of agents) {
    try {
      if (agentFileExists(agent.id)) continue;
      if (syncAgentFile(agent, 'replace')) created++;
    } catch (err: any) {
      logError(`Could not bootstrap persona file for ${agent?.id}`, err?.message ?? String(err));
    }
  }

  if (created) logInfo(`Wrote ${created} agent persona file(s) to ${AGENTS_DIR}`);
  return created;
}

/**
 * Build a new agent from a persona file someone else exported.
 *
 * Sharing an agent is the one capability that works the same whether Alpha is
 * running locally or hosted, because an agent definition is data rather than
 * execution: the recipient runs it on their own CLI, signed into their own
 * subscription. Nothing about the sender's machine needs to travel — and
 * nothing secret does, because `envVars` is not a file field.
 *
 * A new id is minted rather than reusing the sender's. Two people importing the
 * same file onto the same machine should get two agents, not a silent overwrite
 * of the first, and an id from elsewhere would also be an untrusted path
 * segment.
 *
 * Unrecognised values fall back to a default and are reported. The alternative —
 * refusing the whole import over one mistyped `role:` — makes a shared file
 * feel fragile when the fix is obvious and the rest of the definition is fine.
 */
export function agentFromFileContent(
  raw: string,
  existingIds: string[]
): { agent: Agent; warnings: string[] } {
  const { overlay, warnings } = parseAgentFileContent(raw);

  const name = overlay?.name?.trim();
  if (!name) {
    throw new Error(
      'This file has no `name:` in its frontmatter, so there is no agent to import.'
    );
  }

  if (!overlay?.role) warnings.push('No role given — defaulting to Coder.');
  if (!overlay?.modelProvider) warnings.push('No provider given — defaulting to Anthropic.');
  if (!overlay?.systemPrompt) {
    warnings.push('This file has no persona text below the frontmatter.');
  }

  const agent: Agent = {
    id: uniqueAgentId(name, existingIds),
    name,
    role: overlay?.role ?? 'Coder',
    avatar: overlay?.avatar ?? '',
    color: overlay?.color ?? '#6366f1',
    description: overlay?.description ?? '',
    owner: 'You',
    isMine: true,
    modelProvider: overlay?.modelProvider ?? 'Anthropic',
    /**
     * The sender's model when the file names one, blank when it does not.
     *
     * Kept rather than cleared even though it may not exist on the recipient's
     * machine: the model picker already shows an unrecognised value as
     * "(not detected)" instead of dropping it, so keeping it tells the importer
     * what the agent was built for. Nothing runs until a model is chosen anyway.
     */
    modelName: overlay?.modelName ?? '',
    systemPrompt: overlay?.systemPrompt ?? '',
    autonomyLevel: overlay?.autonomyLevel ?? 'Semi-Autonomous (Requires Approval)',
    temperature: overlay?.temperature,
    skills: overlay?.skills ?? [],
    mcpServers: overlay?.mcpServers ?? [],
    // Deliberately not imported: an environment belongs to a machine, and a
    // shared file must never carry someone else's keys.
    envVars: [],
    customCliArgs: '',
    createdAt: new Date().toISOString()
  };

  return { agent, warnings };
}

/**
 * A filesystem-safe id derived from the agent's name, unique on this machine.
 *
 * Readable rather than a uuid because it becomes the persona file's name, and
 * `agent-ada-lovelace.md` is findable in a directory listing where a uuid is not.
 */
export function uniqueAgentId(name: string, existingIds: string[]): string {
  const slug =
    name
      .toLowerCase()
      .replaceAll(/[^a-z0-9]+/g, '-')
      .replaceAll(/^-+|-+$/g, '')
      .slice(0, 40) || 'agent';

  const base = `agent-${slug}`;
  if (!existingIds.includes(base)) return base;

  for (let n = 2; n < 1000; n++) {
    const candidate = `${base}-${n}`;
    if (!existingIds.includes(candidate)) return candidate;
  }

  // A thousand agents of the same name is not a real case; fall back rather
  // than loop forever.
  return `${base}-${Date.now()}`;
}
