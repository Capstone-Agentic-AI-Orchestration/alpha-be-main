import { afterEach, describe, expect, it, vi } from 'vitest';

/**
 * The CI a provisioned repository is born with.
 *
 * The template is alphaorch-workflow's own; what is checked here is that the
 * right one is chosen per stack and that the deploy job can neither fail a
 * new repository's first push (gated) nor appear when it was not wanted.
 */

/** The shape of a customer template, trimmed to what the transforms touch. */
const TEMPLATE = [
  '# Granular frontend React workflow.',
  'name: "Frontend CI"',
  '',
  'jobs:',
  '  unit-tests:',
  '    uses: Capstone-Agentic-AI-Orchestration/alphaorch-workflow/.github/workflows/frontend-tests.yml@v1',
  '',
  '  build:',
  '    needs: [unit-tests]',
  '    runs-on: ubuntu-latest',
  '    steps:',
  '      - run: npm run build',
  '  deploy-vercel:',
  '    needs: [unit-tests, build]',
  "    if: ${{ github.event_name == 'push' && (github.ref_name == 'dev' || github.ref_name == 'main') }}",
  '    uses: Capstone-Agentic-AI-Orchestration/alphaorch-workflow/.github/workflows/vercel-deploy.yml@v1',
  '    with:',
  "      environment: ${{ github.ref_name == 'main' && 'production' || 'preview' }}",
  '    secrets: inherit',
  ''
].join('\n');

function fakeFetch(body = TEMPLATE, status = 200) {
  const urls: string[] = [];
  const impl = (async (url: string | URL) => {
    urls.push(String(url));
    return new Response(body, { status });
  }) as unknown as typeof fetch;
  return { impl, urls };
}

async function load(repo?: string) {
  vi.resetModules();
  if (repo) process.env.ALPHAORCH_WORKFLOW_REPO = repo;
  return import('./ciWorkflows.js');
}

afterEach(() => {
  delete process.env.ALPHAORCH_WORKFLOW_REPO;
});

describe('the CI a new repository gets', () => {
  it('uses the stack’s customer template from alphaorch-workflow@v1', async () => {
    const ci = await load();
    const { impl, urls } = fakeFetch();

    const plan = await ci.buildCiWorkflows({ stack: 'react' }, impl);

    expect(urls).toEqual([
      'https://raw.githubusercontent.com/Capstone-Agentic-AI-Orchestration/alphaorch-workflow/v1/workflow-templates/customer/fe-react.yml'
    ]);
    expect(plan.files.map(file => file.path)).toEqual(['.github/workflows/ci.yml']);
    expect(plan).toMatchObject({
      deployTarget: 'vercel',
      requiredSecrets: ['VERCEL_TOKEN', 'VERCEL_ORG_ID', 'VERCEL_PROJECT_ID'],
      deployVariable: 'ALPHAORCH_DEPLOY'
    });
  });

  it.each([
    ['nodejs', 'be-nodejs.yml'],
    ['nestjs', 'be-nestjs.yml'],
    ['nextjs', 'fe-nextjs.yml'],
    ['react', 'fe-react.yml']
  ] as const)('picks the %s pipeline', async (stack, template) => {
    const ci = await load();
    const backend = template.startsWith('be-');
    const body = backend ? TEMPLATE.replace(/deploy-vercel/g, 'deploy-render') : TEMPLATE;
    const { impl, urls } = fakeFetch(body);

    const plan = await ci.buildCiWorkflows({ stack }, impl);

    expect(urls[0].endsWith(`/customer/${template}`)).toBe(true);
    expect(plan.deployTarget).toBe(backend ? 'render' : 'vercel');
  });

  /** A new repository has no deploy secrets; an ungated deploy would fail its first push. */
  it('keeps the deploy job off until the repository opts in', async () => {
    const ci = await load();
    const { impl } = fakeFetch();

    const yaml = (await ci.buildCiWorkflows({ stack: 'react' }, impl)).files[0].content;

    expect(yaml).toContain(
      "    if: ${{ (github.event_name == 'push' && (github.ref_name == 'dev' || github.ref_name == 'main')) && vars.ALPHAORCH_DEPLOY == 'true' }}"
    );
    expect(yaml.split('\n')[0]).toContain('Generated by Alpha from Capstone-Agentic-AI-Orchestration/alphaorch-workflow@v1');
  });

  it('leaves the deploy job out entirely when deploys are not wanted', async () => {
    const ci = await load();
    const { impl } = fakeFetch();

    const plan = await ci.buildCiWorkflows({ stack: 'react', deploy: false }, impl);
    const yaml = plan.files[0].content;

    expect(yaml).not.toContain('deploy-vercel');
    expect(yaml).toContain('  build:');
    expect(yaml).toContain('      - run: npm run build');
    expect(plan).toMatchObject({ deployTarget: null, requiredSecrets: [], deployVariable: null });
  });

  it('calls a fork’s reusable workflows when Alpha is pointed at a fork', async () => {
    const ci = await load('acme/alphaorch-workflow');
    const { impl, urls } = fakeFetch();

    const yaml = (await ci.buildCiWorkflows({ stack: 'react' }, impl)).files[0].content;

    expect(urls[0]).toContain('/acme/alphaorch-workflow/v1/');
    expect(yaml).toContain('uses: acme/alphaorch-workflow/.github/workflows/frontend-tests.yml@v1');
    expect(yaml).not.toContain('Capstone-Agentic-AI-Orchestration/alphaorch-workflow/');
  });

  it('refuses, before anything is created, when the template cannot be read', async () => {
    const ci = await load();

    await expect(ci.buildCiWorkflows({ stack: 'react' }, fakeFetch('Not Found', 404).impl)).rejects.toThrow(
      /Could not read the CI template .*fe-react\.yml \(HTTP 404\)/
    );
  });
});

describe('editing a workflow', () => {
  it('adds a gate to a job that has no condition yet', async () => {
    const ci = await load();
    const yaml = ['jobs:', '  deploy:', '    uses: x/y/.github/workflows/d.yml@v1', ''].join('\n');

    expect(ci.gateJob(yaml, 'deploy', 'GO')).toBe(
      ['jobs:', '  deploy:', "    if: ${{ vars.GO == 'true' }}", '    uses: x/y/.github/workflows/d.yml@v1', ''].join('\n')
    );
  });

  it('removes a job in the middle without touching its neighbours', async () => {
    const ci = await load();
    const yaml = ['jobs:', '  a:', '    run: 1', '', '  b:', '    run: 2', '', '  c:', '    run: 3', ''].join('\n');

    expect(ci.withoutJob(yaml, 'b')).toBe(['jobs:', '  a:', '    run: 1', '', '  c:', '    run: 3', ''].join('\n'));
  });
});
